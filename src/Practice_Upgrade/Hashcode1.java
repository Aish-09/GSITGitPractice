package practice_Upgrade;

import java.util.Objects;

/**
 * WHAT:
 * Represents an entity model. In real automation frameworks or enterprise applications,
 * domain models require identity definitions based on their data, not their heap address.
 *
 * WHY:
 * Without overriding equals() and hashCode(), Java treats two instances containing identical
 * student data as two completely different entities in collections like HashSet or HashMap.
 */
class Student100 {
    // Encapsulated instance variables
    private int rollno;
    private String name;

    // Explicit constructor initializing the student state
    public Student100(int rollno, String name) {
        super(); // Calls java.lang.Object constructor
        this.rollno = rollno;
        this.name = name;
    }

    // Getters and Setters for field manipulation
    public int getRollno() {
        return rollno;
    }

    public void setRollno(int rollno) {
        this.rollno = rollno;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    /**
     * HOW: Overriding equals()
     * Compares field values (logical equivalence) rather than memory addresses (==).
     */
    @Override
    public boolean equals(Object obj) {
        if (this == obj) return true; // Reference check
        if (obj == null || getClass() != obj.getClass()) return false; // Null and type check
        
        Student100 other = (Student100) obj;
        return rollno == other.rollno && Objects.equals(name, other.name);
    }

    /**
     * HOW: Overriding hashCode()
     * Fulfills the contract: identical objects according to equals() MUST return identical hash codes.
     */
    @Override
    public int hashCode() {
        return Objects.hash(rollno, name);
    }

    @Override
    public String toString() {
        return "Student100[rollno=" + rollno + ", name=" + name + "]";
    }
}

/**
 * WHAT:
 * Demonstration driver executing the core concepts from the class session:
 * 1. String hash collision behavior ("Aa" vs "BB").
 * 2. Custom class hash consistency after correctly adhering to the contract.
 */

//What is hashCode()?
//Definition: An integer representation of an object generated by a hashing algorithm, inherited by every Java object from java.lang.Object.

//String collision detail: In Java, string hash codes are calculated as:
//$$s[0]\times 31^{(n-1)} + s[1]\times 31^{(n-2)} + \dots + s[n-1]$$
//For "Aa": 65 * 31 + 97 = 2015 + 97 = 2112.
//For "BB": 66 * 31 + 66 = 2046 + 66 = 2112.
//Because both evaluate to 2112, this demonstrates that two non-equal objects can produce identical hash codes (a hash collision).


//Why is hashCode() used?Fast Lookup Performance: Hash-based data structures (like HashMap, HashSet, and Hashtable) use this integer to locate 
//the storage bucket in $O(1)$ constant time, avoiding $O(n)$ linear scans across the entire collection.


public class Hashcode1 {

    public static void main(String[] args) {
        
        // -------------------------------------------------------------
        // PART 1: STRING HASH CODE COLLISION DEMONSTRATION
        // -------------------------------------------------------------
        // WHAT: Two distinct strings produces the exact same hash integer.
        // WHY: The formula 31*h + val[i] happens to yield 2112 for both character combinations.
        // HOW: The JVM bucket routing uses this hash, then falls back to equals() to resolve identity.
        String str1 = "Aa";
        String str2 = "BB";

        System.out.println("--- Part 1: String Hash Collision ---");
        System.out.println("str1 (\"Aa\") hashCode : " + str1.hashCode()); // 2112
        System.out.println("str2 (\"BB\") hashCode : " + str2.hashCode()); // 2112
        System.out.println("Are strings equal?     : " + str1.equals(str2)); // false


        // -------------------------------------------------------------
        // PART 2: CUSTOM OBJECT HASH CODE (UPGRADED)
        // -------------------------------------------------------------
        // WHAT: Creating two separate heap objects with identical attributes.
        // WHY: If hashCode() were not overridden, the output would be two arbitrary, different numbers 
        //      (as shown in the instructor console: 1554547125 vs 617901222).
        // HOW: With Objects.hash(rollno, name), both objects now produce the same hash code.
        Student100 s1 = new Student100(1, "Rajat");
        Student100 s2 = new Student100(1, "Rajat");

        System.out.println("\n--- Part 2: Upgraded Custom Class Hash ---");
        System.out.println("s1 hashCode: " + s1.hashCode());
        System.out.println("s2 hashCode: " + s2.hashCode());

        // Verifying logical equality vs reference equality
        System.out.println("Logical Equality (equals) : " + s1.equals(s2)); // true
        System.out.println("Reference Equality (==)    : " + (s1 == s2));    // false (different heap addresses)
    }
}